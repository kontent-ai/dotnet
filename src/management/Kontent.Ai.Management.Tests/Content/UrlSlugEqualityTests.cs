using AwesomeAssertions;
using Kontent.Ai.Management.Models.Content;
using Kontent.Ai.Management.Models.LanguageVariants.Elements;

namespace Kontent.Ai.Management.Tests.Content;

public class UrlSlugEqualityTests
{
    [Fact]
    public void UrlSlugValue_DefaultedMode_EqualsExplicitMode()
    {
        var defaulted = new UrlSlugValue { Value = "on-roasts" };
        var explicitCustom = new UrlSlugValue { Value = "on-roasts", Mode = UrlSlugMode.Custom };

        defaulted.Should().Be(explicitCustom);
        defaulted.GetHashCode().Should().Be(explicitCustom.GetHashCode());
        defaulted.Should().Be((UrlSlugValue)"on-roasts");
    }

    [Fact]
    public void UrlSlugValue_FromEmptyString_EqualsEmptyValue()
    {
        UrlSlugValue converted = "";

        converted.Should().Be(new UrlSlugValue { Value = "" });
        converted.Mode.Should().Be(UrlSlugMode.Autogenerated);
    }

    [Fact]
    public void UrlSlugValue_DifferentMode_IsNotEqual()
        => new UrlSlugValue { Value = "on-roasts" }
            .Should().NotBe(new UrlSlugValue { Value = "on-roasts", Mode = UrlSlugMode.Autogenerated });

    [Fact]
    public void UrlSlugElement_DefaultedMode_EqualsExplicitMode()
    {
        var defaulted = new UrlSlugElement { Element = Reference.ByCodename("slug"), Value = "on-roasts" };
        var explicitCustom = new UrlSlugElement { Element = Reference.ByCodename("slug"), Value = "on-roasts", Mode = UrlSlugMode.Custom };

        defaulted.Should().Be(explicitCustom);
        defaulted.GetHashCode().Should().Be(explicitCustom.GetHashCode());
    }

    [Fact]
    public void UrlSlugElement_DifferentElement_IsNotEqual()
        => new UrlSlugElement { Element = Reference.ByCodename("slug"), Value = "on-roasts" }
            .Should().NotBe(new UrlSlugElement { Element = Reference.ByCodename("other"), Value = "on-roasts" });
}
