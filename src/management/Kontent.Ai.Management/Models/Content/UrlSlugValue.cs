namespace Kontent.Ai.Management.Models.Content;

/// <summary>
/// Value of a url_slug element on a generated content-type record: the slug plus whether it is custom or
/// server-generated. The envelope converter flattens this to a <c>value</c> + sibling <c>mode</c> on the wire.
/// </summary>
/// <remarks>Use this to set a url_slug element on a generated content-type record. To set the same element by hand in the untyped element array instead, use <see cref="LanguageVariants.Elements.UrlSlugElement"/>.</remarks>
public sealed record UrlSlugValue
{
    /// <summary>The slug. For <see cref="UrlSlugMode.Autogenerated"/> it is server-derived and may be omitted on write.</summary>
    [JsonPropertyName("value")]
    public string? Value { get; init; }

    /// <summary>Whether the slug is custom or auto-generated. Defaults to <see cref="UrlSlugMode.Custom"/> when <see cref="Value"/> is non-empty, otherwise to <see cref="UrlSlugMode.Autogenerated"/>. <see cref="UrlSlugMode.Custom"/> with no value clears the slug.</summary>
    [JsonPropertyName("mode")]
    public UrlSlugMode Mode
    {
        get => _mode ?? (string.IsNullOrEmpty(Value) ? UrlSlugMode.Autogenerated : UrlSlugMode.Custom);
        init => _mode = value;
    }

    private readonly UrlSlugMode? _mode;

    /// <inheritdoc />
    public bool Equals(UrlSlugValue? other) => other is not null && Value == other.Value && Mode == other.Mode;

    /// <inheritdoc />
    public override int GetHashCode() => HashCode.Combine(Value, Mode);

    /// <summary>A slug from a string, with <see cref="Mode"/> defaulting as for any other value.</summary>
    public static implicit operator UrlSlugValue(string value) => new() { Value = value };
}
