using System.Text;

namespace Kontent.Ai.Delivery.SourceGeneration.Snapshot;

/// <summary>
/// Writes a model in the shape the model generator tool's Delivery mode emits: a <c>partial record</c> with
/// <c>[ContentTypeCodename]</c>, a codename constant per element and one per type, and <c>[JsonPropertyName]</c>
/// properties, constants in ordinal codename order and properties in ordinal name order. Type names are
/// <c>global::</c>-qualified, unlike the tool's usings, because a model can be named like an SDK type -
/// a content type called <c>asset</c> would otherwise capture every <c>Asset</c> in its namespace.
/// </summary>
internal static class ModelWriter
{
    public static string HintName(ModelSpec model) => $"KontentModels.{model.ClassName}.g.cs";

    public static string Write(ModelSpec model)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by Kontent.Ai.Delivery.SourceGeneration from the content model snapshot.");
        sb.AppendLine("// To extend this record, create a separate partial record with the same name.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {model.Namespace};");
        sb.AppendLine();
        sb.AppendLine($"[global::Kontent.Ai.Delivery.Attributes.ContentTypeCodename(\"{ContentTypeGenerator.EscapeString(model.Codename)}\")]");
        sb.AppendLine($"public partial record {model.ClassName}");
        sb.AppendLine("{");

        foreach (var property in model.Properties.OrderBy(static p => p.Codename, StringComparer.Ordinal))
        {
            sb.AppendLine($"    public const string {property.ConstantIdentifier} = \"{ContentTypeGenerator.EscapeString(property.Codename)}\";");
        }

        sb.AppendLine($"    public const string ContentTypeCodename = \"{ContentTypeGenerator.EscapeString(model.Codename)}\";");

        foreach (var property in model.Properties.OrderBy(static p => p.Identifier, StringComparer.Ordinal))
        {
            var initializer = property.Initializer is null ? string.Empty : $" = {property.Initializer};";

            sb.AppendLine();
            sb.AppendLine($"    [global::System.Text.Json.Serialization.JsonPropertyName(\"{ContentTypeGenerator.EscapeString(property.Codename)}\")]");
            sb.AppendLine($"    public {property.TypeName} {property.Identifier} {{ get; init; }}{initializer}");
        }

        sb.AppendLine("}");

        return sb.ToString();
    }
}
